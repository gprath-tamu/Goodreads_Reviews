"""### RQ2 Feasibility: TF-IDF and Clustering

I run TF-IDF vectorization followed by a small K-Means clustering model to verify that:

- Text preprocessing is valid
- TF-IDF produces a non-empty feature space
- Clustering produces meaningful groupings

This confirms that text-based analysis is feasible for the dataset.
"""

print("===== RQ2: TF-IDF + Clustering Feasibility =====")

text_df = df[df["review_len_tokens"] > 3]

text_sample = text_df.sample(
    n=min(5000, len(text_df)),
    random_state=42
)

vectorizer = TfidfVectorizer(
    stop_words="english",
    max_features=5000,
    min_df=5
)

X = vectorizer.fit_transform(text_sample["review_text"])

kmeans = KMeans(n_clusters=5, random_state=42, n_init=10)
labels = kmeans.fit_predict(X)

print(f"Documents used: {X.shape[0]:,}")
print(f"Vocabulary size: {X.shape[1]:,}")
print(f"Clusters formed: {len(set(labels))}")

# Cluster distribution table
cluster_counts = pd.Series(labels).value_counts().sort_index()
print("\nCluster distribution:")
display(cluster_counts)

# Top terms per cluster
terms = vectorizer.get_feature_names_out()
centroids = kmeans.cluster_centers_.argsort(axis=1)[:, ::-1]

print("\nTop terms per cluster:")
for i in range(3):  # show first 3 clusters
    top_terms = [terms[ind] for ind in centroids[i, :10]]
    print(f"Cluster {i}: {top_terms}")

# Assertions
assert X.shape[0] > 0
assert X.shape[1] > 0
assert len(set(labels)) == 5

print("RQ2 feasibility passed\n")

"""### RQ3 Feasibility: Topic Modeling (LDA)

I run LDA on a sampled subset of reviews to verify that:

- Text data is suitable for topic modeling
- The model converges without errors
- Topic distributions are valid probability distributions

This ensures that topic modeling is computationally feasible and produces interpretable outputs.
"""

print("===== RQ3: LDA Feasibility =====")

lda_sample = df[df["review_len_tokens"] > 3].sample(
    n=min(5000, len(df)),
    random_state=42
)

vectorizer = TfidfVectorizer(
    stop_words="english",
    max_features=3000,
    min_df=5
)

X = vectorizer.fit_transform(lda_sample["review_text"])

lda = LatentDirichletAllocation(
    n_components=5,
    random_state=42
)

doc_topic = lda.fit_transform(X)

print(f"Documents used: {X.shape[0]:,}")
print(f"Vocabulary size: {X.shape[1]:,}")
print(f"Topics: {doc_topic.shape[1]}")

# Topic distribution summary
topic_distribution = pd.DataFrame(doc_topic).mean().sort_values(ascending=False)
print("\nAverage topic distribution:")
display(topic_distribution)

# Top words per topic
terms = vectorizer.get_feature_names_out()

print("\nTop words per topic:")
for i, topic in enumerate(lda.components_[:3]):
    top_idx = topic.argsort()[::-1][:10]
    top_words = [terms[j] for j in top_idx]
    print(f"Topic {i}: {top_words}")

# Assertions
assert doc_topic.shape[0] == X.shape[0]
assert doc_topic.shape[1] == 5
assert np.allclose(doc_topic.sum(axis=1), 1, atol=1e-5)

print("RQ3 feasibility passed\n")

