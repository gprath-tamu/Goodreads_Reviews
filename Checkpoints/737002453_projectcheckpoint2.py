"""## 5. Data Loading and Cleaning"""

# =========================
# 2. Data Loading
# =========================

DATA_PATH = "goodreads_reviews_comics_graphic.json.gz"
rows = []

with gzip.open(DATA_PATH, "rt", encoding="utf-8") as f:
    for line in f:
        rows.append(json.loads(line))

df = pd.DataFrame(rows)

print("Dataset loaded successfully.\n")
print(f"Shape: {df.shape}")
print(f"Columns: {df.columns.tolist()}")


display(df.head(3))
display(df.info())

# =========================
# 3. Data Cleaning & Preprocessing
# =========================

# --- 1. Drop rows with missing critical identifiers ---
# Required for itemset mining (RQ1)
df = df.dropna(subset=["user_id", "book_id"]).copy()

# --- 2. Handle review text ---
# Required for RQ2 (TF-IDF) and RQ3 (LDA)
df["review_text"] = df["review_text"].fillna("").astype(str).str.strip()

# --- 3. Convert numeric fields ---
numeric_cols = ["rating", "n_votes", "n_comments"]
for col in numeric_cols:
    if col in df.columns:
        df[col] = pd.to_numeric(df[col], errors="coerce")

# Keep valid ratings only (1–5)
if "rating" in df.columns:
    df = df[df["rating"].between(1, 5, inclusive="both")]
    df["rating"] = df["rating"].astype(int)

# --- 4. Convert timestamps ---
date_cols = ["date_added", "date_updated", "read_at", "started_at"]
for col in date_cols:
    if col in df.columns:
        df[col] = pd.to_datetime(df[col], errors="coerce")

# --- 5. Create review length feature ---
df["review_len_tokens"] = df["review_text"].str.split().str.len()

# --- 6. Remove very short reviews (noise) ---
# Helps RQ2 (clustering) and RQ3 (LDA)
df = df[df["review_len_tokens"] > 3]

# --- 7. Check duplicates ---
duplicates = df.duplicated().sum()

# --- Final summary ---
print("Data cleaning completed.\n")

print(f"Final shape: {df.shape}")
print(f"Duplicate rows: {duplicates}")

print("\nMissing values (key columns):")
print(df[["user_id", "book_id", "review_text", "rating"]].isna().sum())

